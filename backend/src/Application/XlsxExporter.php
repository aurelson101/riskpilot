<?php

declare(strict_types=1);

namespace App\Application;

final class XlsxExporter
{
    /**
     * @param array<array-key, mixed> $rows     première ligne : en-têtes ; valeurs : nombre, texte, date ou null
     * @param array<string, string>   $metadata lignes de la feuille « Informations » (ex. « Généré par »)
     */
    public function render(string $title, string $organization, array $rows, array $metadata = []): string
    {
        return $this->renderWorkbook($title, $organization, [$title => $rows], $metadata);
    }

    /**
     * Classeur de plusieurs feuilles : une par jeu de lignes, puis la feuille « Informations ».
     *
     * @param array<string, array<array-key, mixed>> $sheets   titre de feuille => lignes (première ligne : en-têtes)
     * @param array<string, string>                  $metadata
     */
    public function renderWorkbook(string $title, string $organization, array $sheets, array $metadata = []): string
    {
        if ([] === $sheets || count($sheets) > 20) {
            throw new \InvalidArgumentException('A workbook needs between one and twenty sheets.');
        }
        $prepared = [];
        $names = [];
        $total = 0;
        foreach ($sheets as $sheetTitle => $rows) {
            $rows = $this->normalize($rows);
            $name = $this->sheetName((string) $sheetTitle);
            $base = $name;
            for ($suffix = 2; in_array(mb_strtolower($name), $names, true); ++$suffix) {
                $name = mb_substr($base, 0, 31 - strlen((string) $suffix) - 1).' '.$suffix;
            }
            $names[] = mb_strtolower($name);
            $prepared[] = ['name' => $name, 'title' => (string) $sheetTitle, 'rows' => $rows];
            $total += count($rows) - 1;
        }

        $path = tempnam(sys_get_temp_dir(), 'riskpilot-xlsx-');
        if (false === $path) {
            throw new \RuntimeException('Unable to create XLSX export.');
        }
        $zip = new \ZipArchive();
        if (true !== $zip->open($path, \ZipArchive::CREATE | \ZipArchive::OVERWRITE)) {
            @unlink($path);
            throw new \RuntimeException('Unable to create XLSX archive.');
        }
        $count = count($prepared);
        $zip->addFromString('[Content_Types].xml', $this->contentTypes($count + 1));
        $zip->addFromString('_rels/.rels', $this->rootRelationships());
        $zip->addFromString('docProps/app.xml', $this->appProperties());
        $zip->addFromString('docProps/core.xml', $this->coreProperties($title, $metadata['Généré par'] ?? $metadata['Generated by'] ?? 'RiskPilot'));
        $zip->addFromString('xl/workbook.xml', $this->workbook(array_column($prepared, 'name')));
        $zip->addFromString('xl/_rels/workbook.xml.rels', $this->workbookRelationships($count + 1));
        $zip->addFromString('xl/styles.xml', $this->styles());
        foreach ($prepared as $index => $sheet) {
            $zip->addFromString(sprintf('xl/worksheets/sheet%d.xml', $index + 1), $this->worksheet($sheet['title'], $organization, $sheet['rows'], $this->columnName(count($sheet['rows'][0]))));
        }
        $zip->addFromString(sprintf('xl/worksheets/sheet%d.xml', $count + 1), $this->informationSheet($title, $organization, $total, $metadata));
        $zip->close();

        $content = file_get_contents($path);
        @unlink($path);
        if (false === $content) {
            throw new \RuntimeException('Unable to read XLSX export.');
        }

        return $content;
    }

    /**
     * @param array<array-key, mixed> $rows
     *
     * @return list<list<int|float|string|\DateTimeInterface|null>>
     */
    private function normalize(array $rows): array
    {
        if ([] === $rows || !array_is_list($rows) || !is_array($rows[0])) {
            throw new \InvalidArgumentException('An XLSX export requires a header row.');
        }
        $columns = count($rows[0]);
        if (0 === $columns || $columns > 16384 || count($rows) > 1048574) {
            throw new \InvalidArgumentException('Export exceeds worksheet dimensions.');
        }
        $normalizedRows = [];
        foreach ($rows as $row) {
            if (!is_array($row)) {
                throw new \InvalidArgumentException('Export rows must be arrays.');
            }
            if (!array_is_list($row) || count($row) !== $columns) {
                throw new \InvalidArgumentException('Export rows must match the header columns.');
            }
            $normalizedRow = [];
            foreach ($row as $value) {
                if ((!is_int($value) && !is_float($value) && !is_string($value) && !$value instanceof \DateTimeInterface && null !== $value)
                    || (is_float($value) && !is_finite($value)) || (is_string($value) && !mb_check_encoding($value, 'UTF-8'))) {
                    throw new \InvalidArgumentException('Invalid export cell value.');
                }
                if (is_string($value) && mb_strlen($value) > 32767) {
                    throw new \InvalidArgumentException('Export cell exceeds the Excel text limit.');
                }
                $normalizedRow[] = $value;
            }
            $normalizedRows[] = $normalizedRow;
        }

        return $normalizedRows;
    }

    private function sheetName(string $title): string
    {
        $name = trim(preg_replace('~[\\\\/?*\[\]:\x00-\x1F]~u', ' ', $title) ?? '', " '");

        return mb_substr('' === $name ? 'RiskPilot' : $name, 0, 31);
    }

    /** @param list<list<int|float|string|\DateTimeInterface|null>> $rows */
    private function worksheet(string $title, string $organization, array $rows, string $lastColumn): string
    {
        $xml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>';
        $xml .= '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">';
        $xml .= '<sheetPr><pageSetUpPr fitToPage="1"/></sheetPr>';
        $xml .= sprintf('<dimension ref="A1:%s%d"/>', $lastColumn, count($rows) + 2);
        $xml .= '<sheetViews><sheetView workbookViewId="0"><pane ySplit="3" topLeftCell="A4" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>';
        $xml .= '<cols>';
        foreach ($rows[0] as $index => $header) {
            $width = $this->columnWidth($rows, $index);
            $xml .= sprintf('<col min="%d" max="%d" width="%d" customWidth="1"/>', $index + 1, $index + 1, $width);
        }
        $xml .= '</cols><sheetData>';
        $xml .= '<row r="1" ht="28" customHeight="1">'.$this->inlineCell('A1', $title, 1).'</row>';
        $xml .= '<row r="2" ht="22" customHeight="1">'.$this->inlineCell('A2', sprintf('%s · %s', $organization, (new \DateTimeImmutable())->format('d/m/Y H:i')), 2).'</row>';
        foreach ($rows as $rowIndex => $row) {
            $excelRow = $rowIndex + 3;
            $style = 0 === $rowIndex ? 3 : (0 === $rowIndex % 2 ? 4 : 5);
            $xml .= sprintf('<row r="%d"%s>', $excelRow, 0 === $rowIndex ? ' ht="24" customHeight="1"' : '');
            foreach ($row as $columnIndex => $value) {
                $ref = $this->columnName($columnIndex + 1).$excelRow;
                if (0 !== $rowIndex && (is_int($value) || is_float($value))) {
                    $xml .= sprintf('<c r="%s" s="6" t="n"><v>%s</v></c>', $ref, $value);
                } elseif (0 !== $rowIndex && $value instanceof \DateTimeInterface) {
                    $serial = $this->serial($value);
                    $xml .= sprintf('<c r="%s" s="%d" t="n"><v>%s</v></c>', $ref, is_int($serial) ? 7 : 8, $serial);
                } else {
                    // Les cellules texte ne sont jamais évaluées comme formules : aucune apostrophe de protection n'est ajoutée.
                    $xml .= $this->inlineCell($ref, $this->text($value), $style);
                }
            }
            $xml .= '</row>';
        }
        $xml .= '</sheetData>';
        $xml .= sprintf('<autoFilter ref="A3:%s%d"/>', $lastColumn, count($rows) + 2);
        if ('A' !== $lastColumn) {
            $xml .= sprintf('<mergeCells count="2"><mergeCell ref="A1:%s1"/><mergeCell ref="A2:%s2"/></mergeCells>', $lastColumn, $lastColumn);
        }
        $xml .= '<printOptions horizontalCentered="1"/>';
        $xml .= '<pageMargins left="0.25" right="0.25" top="0.5" bottom="0.5" header="0.2" footer="0.2"/><pageSetup orientation="landscape" fitToWidth="1" fitToHeight="0"/>';
        $xml .= '<headerFooter><oddHeader>&amp;C&amp;B'.$this->xml(str_replace('&', '&&', $title)).'&amp;B</oddHeader><oddFooter>&amp;L'.$this->xml(str_replace('&', '&&', $organization)).'&amp;RPage &amp;P / &amp;N</oddFooter></headerFooter>';
        $xml .= '</worksheet>';

        return $xml;
    }

    /** @param array<string, string> $metadata */
    private function informationSheet(string $title, string $organization, int $records, array $metadata): string
    {
        $items = [['Document', $title], ['Organisation', $organization], ['Généré le', (new \DateTimeImmutable())->format('d/m/Y H:i')], ['Enregistrements', (string) $records]];
        foreach ($metadata as $label => $value) {
            $items[] = [(string) $label, $value];
        }
        $items[] = ['Avertissement', 'Données visibles par l’utilisateur au moment de l’export ; à traiter selon la classification de l’organisation.'];
        $xml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><cols><col min="1" max="1" width="22" customWidth="1"/><col min="2" max="2" width="80" customWidth="1"/></cols><sheetData>';
        foreach ($items as $index => [$label, $value]) {
            $row = $index + 1;
            $xml .= sprintf('<row r="%d">%s%s</row>', $row, $this->inlineCell('A'.$row, $label, 3), $this->inlineCell('B'.$row, $value, 5));
        }

        return $xml.'</sheetData></worksheet>';
    }

    /** Numéro de série Excel (jours depuis 1899-12-30), à partir de l'heure murale de la date. */
    private function serial(\DateTimeInterface $date): int|float
    {
        $wall = new \DateTimeImmutable($date->format('Y-m-d H:i:s'), new \DateTimeZone('UTC'));
        $midnight = $wall->setTime(0, 0);
        $days = intdiv($midnight->getTimestamp(), 86400) + 25569;
        $seconds = $wall->getTimestamp() - $midnight->getTimestamp();

        return 0 === $seconds ? $days : $days + $seconds / 86400;
    }

    private function inlineCell(string $reference, string $value, int $style): string
    {
        return sprintf('<c r="%s" s="%d" t="inlineStr"><is><t xml:space="preserve">%s</t></is></c>', $reference, $style, $this->xml($value));
    }

    /** @param list<list<int|float|string|\DateTimeInterface|null>> $rows */
    private function columnWidth(array $rows, int $column): int
    {
        $length = 0;
        foreach (array_slice($rows, 0, 200) as $row) {
            $value = $row[$column] ?? '';
            $length = max($length, $value instanceof \DateTimeInterface ? 10 : (int) max(array_map('mb_strlen', explode("\n", (string) $value))));
        }

        return max(12, min(46, $length + 3));
    }

    private function xml(string $value): string
    {
        $value = preg_replace('/[^\x{9}\x{A}\x{D}\x{20}-\x{D7FF}\x{E000}-\x{FFFD}\x{10000}-\x{10FFFF}]/u', '', $value) ?? '';

        return htmlspecialchars($value, ENT_XML1 | ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }

    private function text(int|float|string|\DateTimeInterface|null $value): string
    {
        return $value instanceof \DateTimeInterface ? $value->format('d/m/Y') : (string) $value;
    }

    private function columnName(int $index): string
    {
        $name = '';
        while ($index > 0) {
            --$index;
            $name = chr(65 + ($index % 26)).$name;
            $index = intdiv($index, 26);
        }

        return $name;
    }

    private function contentTypes(int $sheets): string
    {
        return '<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'.$this->sheetTypes($sheets).'<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/><Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/><Override PartName="/docProps/app.xml" ContentType="application/vnd.openxmlformats-officedocument.extended-properties+xml"/></Types>';
    }

    private function sheetTypes(int $sheets): string
    {
        $items = '';
        for ($index = 1; $index <= $sheets; ++$index) {
            $items .= sprintf('<Override PartName="/xl/worksheets/sheet%d.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>', $index);
        }

        return $items;
    }

    private function rootRelationships(): string
    {
        return '<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/><Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/><Relationship Id="rId3" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/extended-properties" Target="docProps/app.xml"/></Relationships>';
    }

    /** @param list<string> $names */
    private function workbook(array $names): string
    {
        $sheets = '';
        $titles = '';
        foreach ($names as $index => $name) {
            $sheets .= sprintf('<sheet name="%s" sheetId="%d" r:id="rId%d"/>', $this->xml($name), $index + 1, $index + 2);
            $titles .= sprintf('<definedName name="_xlnm.Print_Titles" localSheetId="%d">%s</definedName>', $index, $this->xml("'".str_replace("'", "''", $name)."'!\$1:\$3"));
        }
        $info = count($names) + 1;

        return '<?xml version="1.0" encoding="UTF-8"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>'.$sheets.'<sheet name="Informations" sheetId="'.$info.'" r:id="rId'.($info + 1).'"/></sheets><definedNames>'.$titles.'</definedNames></workbook>';
    }

    private function workbookRelationships(int $sheets): string
    {
        $items = '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>';
        for ($index = 1; $index <= $sheets; ++$index) {
            $items .= sprintf('<Relationship Id="rId%d" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet%d.xml"/>', $index + 1, $index);
        }

        return '<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'.$items.'</Relationships>';
    }

